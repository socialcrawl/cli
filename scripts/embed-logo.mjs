// Writes src/render/logo.ts from assets/socialcrawl-lockup.png, so every report and card
// carries the logo inside itself and fetches nothing. Run after changing the PNG:
//   node scripts/embed-logo.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const png = readFileSync(path.join(root, "assets", "socialcrawl-lockup.png"));
if (png.toString("ascii", 1, 4) !== "PNG") throw new Error("assets/socialcrawl-lockup.png is not a PNG");
const width = png.readUInt32BE(16);
const height = png.readUInt32BE(20);
const out = [
  "// Generated by scripts/embed-logo.mjs from assets/socialcrawl-lockup.png. Do not edit.",
  "// The SocialCrawl name and logo are not covered by this repository's MIT licence.",
  `export const LOGO_WIDTH = ${width};`,
  `export const LOGO_HEIGHT = ${height};`,
  `export const LOGO_DATA_URI = "data:image/png;base64,${png.toString("base64")}";`,
  "",
].join("\n");
writeFileSync(path.join(root, "src", "render", "logo.ts"), out);
console.log(`src/render/logo.ts: ${width}x${height}, ${png.length} bytes`);
